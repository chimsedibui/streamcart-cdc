"""Silver: the streaming datasets. Scaffolds their specs from the source schema and renders flink/sql/silver.sql, the
one Flink job that upserts every silver.<table> from its cdc.ecommerce.<table> topic.
"""

from .source import ROOT
from .specs import PIPELINES, Spec

OUT = ROOT / "flink" / "sql" / "silver.sql"

# PostgreSQL type -> Flink type, for the Debezium JSON the connector writes (decimal.handling.mode=string,
# time.precision.mode=connect, timestamptz as ISO-8601 strings with Z). Anything else fails validation.
FLINK_TYPES = {
    "uuid": "STRING", "character varying": "STRING", "text": "STRING", "name": "STRING", "jsonb": "STRING",
    "pg_lsn": "STRING", "numeric": "STRING",
    "bigint": "BIGINT", "integer": "INT", "smallint": "SMALLINT", "boolean": "BOOLEAN",
    "double precision": "DOUBLE", "timestamp with time zone": "TIMESTAMP_LTZ(6)",
}
# ... and the Trino type the same column has once Flink wrote it to Iceberg (tests build fixtures with these)
TRINO_TYPES = {
    "STRING": "varchar", "BIGINT": "bigint", "INT": "integer", "SMALLINT": "smallint", "BOOLEAN": "boolean",
    "DOUBLE": "double", "TIMESTAMP_LTZ(6)": "timestamp(6) with time zone",
}
DEFAULT_OWNER = "data-platform"
DEFAULT_FRESHNESS = {"warn_after": "15m", "error_after": "1h"}


def trino_columns(spec: Spec) -> dict[str, str]:
    cols = {n: TRINO_TYPES[FLINK_TYPES[t]] for n, t in spec.columns.items()}
    cols["_source_ts"] = "timestamp(3) with time zone"
    return cols


def scaffold(table: dict) -> str:
    """A new silver spec for a source table: everything the source says, plus defaults to review."""
    name = table["table_name"]
    columns = "\n".join(f"  {c['name']}: {c['type']}" for c in table["columns"])
    return f"""# Columns, key and replica identity mirror the source (platform/cli.py validate checks them);
# owner, description, expectations and freshness are ours to edit.
dataset: silver.{name}
owner: {DEFAULT_OWNER}
description: Current state of ecommerce.{name}, one row per primary key.
mode: streaming
from: kafka:cdc.ecommerce.{name}
primary_key: [{", ".join(table["primary_key"])}]
replica_identity: {table["replica_identity"]}
columns:
{columns}
freshness: {{warn_after: {DEFAULT_FRESHNESS["warn_after"]}, error_after: {DEFAULT_FRESHNESS["error_after"]}}}
"""


def spec_path(table_name: str):
    return PIPELINES / "silver" / f"{table_name}.yml"


def render(specs: list[Spec]) -> str:
    out = ["""-- GENERATED by platform/cli.py generate from pipelines/silver/*.yml. Do not edit.
-- One Flink job: every silver dataset, Kafka (Debezium JSON changelog) -> Iceberg v2 upsert by primary key.

-- (sql-client: comments only on their own lines; text after a ';' joins the next statement)
SET 'pipeline.name' = 'silver-cdc';
-- Iceberg commits once per checkpoint
SET 'execution.checkpointing.interval' = '30s';
-- the Iceberg upsert writer already keeps the last row per key
SET 'table.exec.sink.upsert-materialize' = 'NONE';

-- credential: the Polaris principal `flink`, filled in from its secret file by submit.sh
CREATE CATALOG lakehouse WITH (
  'type' = 'iceberg',
  'catalog-type' = 'rest',
  'uri' = 'http://polaris:8181/api/catalog',
  'warehouse' = 'lakehouse',
  'credential' = '${POLARIS_CREDENTIAL}',
  'scope' = 'PRINCIPAL_ROLE:ALL',
  'io-impl' = 'org.apache.iceberg.aws.s3.S3FileIO',
  's3.endpoint' = 'http://seaweedfs:8333',
  's3.path-style-access' = 'true'
);
CREATE DATABASE IF NOT EXISTS lakehouse.silver;
"""]
    inserts = []
    for spec in specs:
        name, pk = spec.name, spec.primary_key
        typed = [(n, FLINK_TYPES[t]) for n, t in spec.columns.items()]
        key = ", ".join(q(k) for k in pk)
        src_cols = ",\n".join(f"  {q(n)} {ty}" for n, ty in typed)
        sink_cols = ",\n".join(f"  {q(n)} {ty}{' NOT NULL' if n in pk else ''}" for n, ty in typed)
        out.append(f"""
-- {name}
CREATE TEMPORARY TABLE {q('src_' + name)} (
{src_cols},
  `_source_ts` TIMESTAMP_LTZ(3) METADATA FROM 'value.source.timestamp' VIRTUAL
) WITH (
  'connector' = 'kafka',
  'topic' = '{spec.topic}',
  'properties.bootstrap.servers' = 'kafka:9092',
  'properties.group.id' = 'flink-silver',
  'properties.auto.offset.reset' = 'earliest',
  'scan.startup.mode' = 'group-offsets',
  'format' = 'debezium-json',
  'debezium-json.timestamp-format.standard' = 'ISO-8601'
);
CREATE TABLE IF NOT EXISTS lakehouse.silver.{q(name)} (
{sink_cols},
  `_source_ts` TIMESTAMP_LTZ(3),
  PRIMARY KEY ({key}) NOT ENFORCED
) WITH (
  'format-version' = '2',
  'write.upsert.enabled' = 'true',
  'write.parquet.compression-codec' = 'zstd'
);""")
        inserts.append(f"INSERT INTO lakehouse.silver.{q(name)} SELECT * FROM {q('src_' + name)};")
    out.append("\nEXECUTE STATEMENT SET BEGIN\n" + "\n".join(inserts) + "\nEND;\n")
    return "\n".join(out)


def q(name: str) -> str:
    return f"`{name}`"
