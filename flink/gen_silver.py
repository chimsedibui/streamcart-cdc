#!/usr/bin/env python3
"""Generates flink/sql/silver.sql, the Flink job that keeps lakehouse.silver.<table> equal to the source tables.

The column list, types and primary keys come from the source database itself (built from source/postgres/init.sql),
and the table list from the Debezium connector's capture filter, so a schema change upstream either regenerates
cleanly or fails here, before anything runs:

    flink/gen_silver.py            # write flink/sql/silver.sql
    flink/gen_silver.py --check    # exit 1 if silver.sql is stale (CI: the source contract)

PSQL is the command that runs a query, by default against the compose database:
    PSQL="psql postgresql://admin:admin@localhost:5432/enterprise_db" flink/gen_silver.py --check
"""

import json
import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "flink" / "sql" / "silver.sql"
CONNECTOR = ROOT / "debezium" / "postgres-connector.json"
PSQL = os.getenv("PSQL", "docker exec -i streamcart-postgres-1 psql -U admin -d enterprise_db")

# Captured, but not business state: the outbox is rerouted to events.* and the signal table drives snapshots
NOT_SILVER = {"outbox_events", "debezium_signals"}

# PostgreSQL type -> Flink type, for the Debezium JSON the connector writes (decimal.handling.mode=string,
# time.precision.mode=connect, timestamptz as ISO-8601 strings with Z). Anything else fails generation.
TYPES = {
    "uuid": "STRING", "character varying": "STRING", "text": "STRING", "name": "STRING", "jsonb": "STRING",
    "pg_lsn": "STRING", "numeric": "STRING",
    "bigint": "BIGINT", "integer": "INT", "smallint": "SMALLINT", "boolean": "BOOLEAN",
    "double precision": "DOUBLE", "timestamp with time zone": "TIMESTAMP_LTZ(6)",
}

CATALOG_QUERY = """
SELECT json_agg(t ORDER BY t.table_name) FROM (
  SELECT c.table_name,
         json_agg(json_build_object('name', c.column_name, 'type', c.data_type) ORDER BY c.ordinal_position) AS columns,
         (SELECT json_agg(k.column_name ORDER BY k.ordinal_position)
            FROM information_schema.table_constraints tc
            JOIN information_schema.key_column_usage k USING (constraint_schema, constraint_name)
           WHERE tc.table_schema = 'ecommerce' AND tc.table_name = c.table_name
             AND tc.constraint_type = 'PRIMARY KEY') AS primary_key
    FROM information_schema.columns c
    JOIN information_schema.tables tb USING (table_schema, table_name)
   WHERE c.table_schema = 'ecommerce' AND tb.table_type = 'BASE TABLE'
   GROUP BY c.table_name) t
"""


def source_tables() -> list[dict]:
    out = subprocess.run(shlex.split(PSQL) + ["-At", "-v", "ON_ERROR_STOP=1"], input=CATALOG_QUERY,
                         capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def captured(tables: list[dict]) -> list[dict]:
    include = json.loads(CONNECTOR.read_text())["config"]["table.include.list"]
    pattern = re.compile(include)    # the connector's Java regex; its lookahead is valid Python too
    return [t for t in tables if pattern.fullmatch(f"ecommerce.{t['table_name']}") and t["table_name"] not in NOT_SILVER]


def flink_type(table: str, col: dict) -> str:
    try:
        return TYPES[col["type"]]
    except KeyError:
        sys.exit(f"{table}.{col['name']}: no Flink mapping for PostgreSQL type '{col['type']}' (add it to TYPES)")


def q(name: str) -> str:
    return f"`{name}`"


def render(tables: list[dict]) -> str:
    out = [f"""-- GENERATED by flink/gen_silver.py from the source schema and the connector filter. Do not edit.
-- One Flink job: every captured business table, Kafka (Debezium JSON changelog) -> Iceberg v2 upsert by primary key.

-- (sql-client: comments only on their own lines; text after a ';' joins the next statement)
SET 'pipeline.name' = 'silver-cdc';
-- Iceberg commits once per checkpoint
SET 'execution.checkpointing.interval' = '30s';
-- the Iceberg upsert writer already keeps the last row per key
SET 'table.exec.sink.upsert-materialize' = 'NONE';

CREATE CATALOG lakehouse WITH (
  'type' = 'iceberg',
  'catalog-type' = 'rest',
  'uri' = 'http://iceberg-rest:8181',
  'warehouse' = 's3://warehouse/',
  'io-impl' = 'org.apache.iceberg.aws.s3.S3FileIO',
  's3.endpoint' = 'http://seaweedfs:8333',
  's3.path-style-access' = 'true'
);
CREATE DATABASE IF NOT EXISTS lakehouse.silver;
"""]
    inserts = []
    for t in tables:
        name, cols, pk = t["table_name"], t["columns"], t["primary_key"]
        if not pk:
            sys.exit(f"{name}: no primary key, cannot upsert")
        typed = [(c["name"], flink_type(name, c)) for c in cols]
        key = ", ".join(q(k) for k in pk)
        src_cols = ",\n".join(f"  {q(n)} {ty}" for n, ty in typed)
        sink_cols = ",\n".join(f"  {q(n)} {ty}{' NOT NULL' if n in pk else ''}" for n, ty in typed)
        out.append(f"""
-- {name}
CREATE TEMPORARY TABLE {q('src_' + name)} (
{src_cols},
  `_source_ts` TIMESTAMP_LTZ(3) METADATA FROM 'value.source.timestamp' VIRTUAL
) WITH (
  'connector' = 'kafka',
  'topic' = 'cdc.ecommerce.{name}',
  'properties.bootstrap.servers' = 'kafka:9092',
  'properties.group.id' = 'flink-silver',
  'properties.auto.offset.reset' = 'earliest',
  'scan.startup.mode' = 'group-offsets',
  'format' = 'debezium-json',
  'debezium-json.timestamp-format.standard' = 'ISO-8601'
);
CREATE TABLE IF NOT EXISTS lakehouse.silver.{q(name)} (
{sink_cols},
  `_source_ts` TIMESTAMP_LTZ(3),
  PRIMARY KEY ({key}) NOT ENFORCED
) WITH (
  'format-version' = '2',
  'write.upsert.enabled' = 'true',
  'write.parquet.compression-codec' = 'zstd'
);""")
        inserts.append(f"INSERT INTO lakehouse.silver.{q(name)} SELECT * FROM {q('src_' + name)};")
    out.append("\nEXECUTE STATEMENT SET BEGIN\n" + "\n".join(inserts) + "\nEND;\n")
    return "\n".join(out)


def main():
    sql = render(captured(source_tables()))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != sql:
            sys.exit(f"{OUT.relative_to(ROOT)} is stale: the source schema changed. Run flink/gen_silver.py")
        print(f"{OUT.relative_to(ROOT)} matches the source schema")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(sql)
    print(f"wrote {OUT.relative_to(ROOT)}: {sql.count('INSERT INTO')} tables")


if __name__ == "__main__":
    main()
